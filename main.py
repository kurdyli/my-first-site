import sqlite3
import os
from pathlib import Path

from fastapi import FastAPI, HTTPException
from fastapi.responses import FileResponse
from pydantic import BaseModel
import psycopg

app = FastAPI()

BASE_DIR = Path(__file__).resolve().parent
DATABASE_PATH = BASE_DIR / "site.db"
DATABASE_URL = os.getenv("DATABASE_URL")


def connect_database():
    if DATABASE_URL:
        return psycopg.connect(DATABASE_URL, sslmode="require")
    return sqlite3.connect(DATABASE_PATH)


def placeholder():
    return "%s" if DATABASE_URL else "?"


class MessageCreate(BaseModel):
    text: str


def create_database():
    connection = connect_database()
    cursor = connection.cursor()

    id_column = "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if DATABASE_URL else "INTEGER PRIMARY KEY"
    cursor.execute(f"""
        CREATE TABLE IF NOT EXISTS messages (
            id {id_column},
            text TEXT NOT NULL,
            author TEXT NOT NULL
        )
    """)

    cursor.execute("SELECT COUNT(*) FROM messages")
    messages_count = cursor.fetchone()[0]

    if messages_count == 0:
        cursor.execute(
            f"INSERT INTO messages (text, author) VALUES ({placeholder()}, {placeholder()})",
            ("Привет из SQLite-базы данных!", "Python + SQLite"),
        )

    connection.commit()
    connection.close()


create_database()


@app.get("/api/messages")
def get_messages():
    connection = connect_database()
    cursor = connection.cursor()

    cursor.execute("SELECT id, text, author FROM messages ORDER BY id DESC")
    messages = cursor.fetchall()

    connection.close()

    return [
        {"id": message[0], "text": message[1], "author": message[2]}
        for message in messages
    ]


@app.post("/api/messages", status_code=201)
def create_message(message: MessageCreate):
    text = message.text.strip()

    if not text:
        raise HTTPException(status_code=400, detail="Сообщение не может быть пустым")

    if len(text) > 200:
        raise HTTPException(status_code=400, detail="Сообщение длиннее 200 символов")

    connection = connect_database()
    cursor = connection.cursor()

    cursor.execute(
        f"INSERT INTO messages (text, author) VALUES ({placeholder()}, {placeholder()}) RETURNING id" if DATABASE_URL else "INSERT INTO messages (text, author) VALUES (?, ?)",
        (text, "Гость"),
    )
    message_id = cursor.fetchone()[0] if DATABASE_URL else cursor.lastrowid

    connection.commit()
    connection.close()

    return {"id": message_id, "text": text, "author": "Гость"}


@app.get("/")
def get_site():
    return FileResponse(BASE_DIR / "index.html")


@app.get("/styles.css")
def get_styles():
    return FileResponse(BASE_DIR / "styles.css", media_type="text/css")
